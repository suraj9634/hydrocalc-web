    // Linear interpolation
static double _interpolate(
  double x,
  double x1,
  double x2,
  double y1,
  double y2,
) {
  if (x1 == x2) return y1;
  return y1 + ((x - x1) / (x2 - x1)) * (y2 - y1);
}

// Main discharge calculation
static double getDischarge({
  required double reservoirLevel,
  required double gateOpeningMm,
}) {
  // Convert mm to metres
  double opening = gateOpeningMm / 1000.0;

  // Validation
  if (opening < 0.00 || opening > 8.00) {
    return 0.0;
  }

  if (reservoirLevel < reservoirLevels.first ||
      reservoirLevel > reservoirLevels.last) {
    return 0.0;
  }

  // Find surrounding gate openings
  List<double> openings = dischargeTable.keys.toList()..sort();

  double lowerOpening = openings.first;
  double upperOpening = openings.last;

  for (int i = 0; i < openings.length - 1; i++) {
    if (opening >= openings[i] && opening <= openings[i + 1]) {
      lowerOpening = openings[i];
      upperOpening = openings[i + 1];
      break;
    }
  }

  // Find surrounding reservoir levels
  double lowerLevel = reservoirLevels.first;
  double upperLevel = reservoirLevels.last;

  for (int i = 0; i < reservoirLevels.length - 1; i++) {
    if (reservoirLevel >= reservoirLevels[i] &&
        reservoirLevel <= reservoirLevels[i + 1]) {
      lowerLevel = reservoirLevels[i];
      upperLevel = reservoirLevels[i + 1];
      break;
    }
  }

  int lowerIndex = reservoirLevels.indexOf(lowerLevel);
  int upperIndex = reservoirLevels.indexOf(upperLevel);

  double q11 = dischargeTable[lowerOpening]![lowerIndex];
  double q12 = dischargeTable[lowerOpening]![upperIndex];

  double q21 = dischargeTable[upperOpening]![lowerIndex];
  double q22 = dischargeTable[upperOpening]![upperIndex];

  // Interpolate for lower opening
  double lowerResult = _interpolate(
    reservoirLevel,
    lowerLevel,
    upperLevel,
    q11,
    q12,
  );

  // Interpolate for upper opening
  double upperResult = _interpolate(
    reservoirLevel,
    lowerLevel,
    upperLevel,
    q21,
    q22,
  );

  // Final interpolation between openings
  return _interpolate(
    opening,
    lowerOpening,
    upperOpening,
    lowerResult,
    upperResult,
  );
}
