  static double _interpolate(
    double x,
    double x1,
    double x2,
    double y1,
    double y2,
  ) {
    if (x1 == x2) return y1;
    return y1 + ((x - x1) / (x2 - x1)) * (y2 - y1);
  }

  /// Calculates discharge per radial gate based on selected rating chart
  static double getDischarge({
    required double reservoirLevel,
    required double gateOpeningMm,
    RatingChartType chartType = RatingChartType.legacy,
  }) {
    double opening = gateOpeningMm / 1000.0;

    // Gate closed
    if (opening <= 0.0) {
      return 0.0;
    }

    final levels = (chartType == RatingChartType.legacy)
        ? legacyReservoirLevels
        : newReservoirLevels;

    final table = (chartType == RatingChartType.legacy)
        ? legacyDischargeTable
        : newDischargeTable;

    // Check reservoir level boundaries
    if (reservoirLevel < levels.first || reservoirLevel > levels.last) {
      return 0.0;
    }

    List<double> openings = table.keys.toList()..sort();

    // Opening exceeds table upper limit
    if (opening > openings.last) {
      return 0.0;
    }

    // Direct key match
    if (table.containsKey(opening)) {
      return _interpolateLevel(table[opening]!, levels, reservoirLevel);
    }

    // Bracket between gate openings
    double lowerOpening = openings.first;
    double upperOpening = openings.last;

    for (int i = 0; i < openings.length - 1; i++) {
      if (opening >= openings[i] && opening <= openings[i + 1]) {
        lowerOpening = openings[i];
        upperOpening = openings[i + 1];
        break;
      }
    }

    double lowerResult = _interpolateLevel(table[lowerOpening]!, levels, reservoirLevel);
    double upperResult = _interpolateLevel(table[upperOpening]!, levels, reservoirLevel);

    return _interpolate(opening, lowerOpening, upperOpening, lowerResult, upperResult);
  }

  static double _interpolateLevel(
    List<double> discharges,
    List<double> levels,
    double reservoirLevel,
  ) {
    int exactIdx = levels.indexOf(reservoirLevel);
    if (exactIdx != -1 && exactIdx < discharges.length) {
      return discharges[exactIdx];
    }

    double lowerLevel = levels.first;
    double upperLevel = levels.last;

    for (int i = 0; i < levels.length - 1; i++) {
      if (reservoirLevel >= levels[i] && reservoirLevel <= levels[i + 1]) {
        lowerLevel = levels[i];
        upperLevel = levels[i + 1];
        break;
      }
    }

    int lowerIdx = levels.indexOf(lowerLevel);
    int upperIdx = levels.indexOf(upperLevel);

    if (lowerIdx >= discharges.length || upperIdx >= discharges.length) {
      return 0.0;
    }

    double q1 = discharges[lowerIdx];
    double q2 = discharges[upperIdx];

    return _interpolate(reservoirLevel, lowerLevel, upperLevel, q1, q2);
  }
